export type CopyKey = keyof typeof copy;
export function translate(language: Language, key: CopyKey): string {
  if (language === "ar") return copy[key][0];
  if (language === "en") return copy[key][1];
  return dictionaries.get()[language]?.[key] || copy[key][1];
}
export function useI18n() {
  const language = useContext(LanguageContext);
  useSyncExternalStore(dictionaries.subscribe, dictionaries.get, dictionaries.get); // re-render when a dictionary loads
  return { language, t: (key: CopyKey) => translate(language, key) };
}