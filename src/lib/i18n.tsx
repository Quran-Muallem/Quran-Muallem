/** True when most letters of a text are Arabic-script (Arabic, Urdu): show it right to left. */
export const isRtlText = (text: string) => {
  const rtl = (text.match(/[\u0590-\u08FF\uFB1D-\uFEFC]/g) ?? []).length;
  const ltr = (text.match(/[A-Za-z\u00C0-\u024F\u0400-\u04FF\u0980-\u09FF]/g) ?? []).length;
  return rtl > ltr;
};
