#!/usr/bin/env node
/**
 * Builds the legal texts from legal/*.{en,ar}.md:
 *   src/lib/legalTexts.ts        – the Markdown, bundled into the app (Settings → Legal)
 *   public/legal/<doc>.html      – bilingual static pages (English | Arabic) for the store listing URL
 *   public/legal/index.html      – links to all three
 *
 *   npm run legal        (run again after editing a .md file)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const DOCS = [
  { id: "privacy", en: "Privacy Policy", ar: "سياسة الخصوصية" },
  { id: "terms", en: "Terms of Service", ar: "شروط الخدمة" },
];

const texts = {};
// Further languages are optional: legal/<doc>.<code>.md (e.g. privacy.de.md). Without a file the app shows English.
const EXTRA = ["de", "fr", "tr", "ur", "id", "ms", "es", "ru", "bn", "sq", "bs"];
for (const d of DOCS) {
  texts[d.id] = { en: readFileSync(`legal/${d.id}.en.md`, "utf8"), ar: readFileSync(`legal/${d.id}.ar.md`, "utf8") };
  for (const code of EXTRA) if (existsSync(`legal/${d.id}.${code}.md`)) texts[d.id][code] = readFileSync(`legal/${d.id}.${code}.md`, "utf8");
}

writeFileSync("src/lib/legalTexts.ts",
  `// Generated by scripts/build-legal.mjs from legal/*.md – do not edit by hand, run \`npm run legal\`.\n` +
  `export const LEGAL_TEXTS = ${JSON.stringify(texts, null, 2)} as const;\n`);

/* ---------- tiny Markdown → HTML (headings, paragraphs, lists, tables, quotes, bold, italics) ---------- */
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const inline = (s) => esc(s).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>").replace(/\*(.+?)\*/g, "<em>$1</em>");
function md(src) {
  const out = []; const lines = src.split(/\r?\n/);
  for (let i = 0; i < lines.length;) {
    const l = lines[i];
    if (!l.trim()) { i++; continue; }
    const h = l.match(/^(#{1,3})\s+(.*)/);
    if (h) { out.push(`<h${h[1].length}>${inline(h[2])}</h${h[1].length}>`); i++; continue; }
    if (l.startsWith("|")) {
      const rows = []; while (i < lines.length && lines[i].startsWith("|")) rows.push(lines[i++]);
      const cells = (r) => r.replace(/^\||\|$/g, "").split("|").map((c) => inline(c.trim()));
      const [head, , ...body] = rows;
      out.push(`<table><thead><tr>${cells(head).map((c) => `<th>${c}</th>`).join("")}</tr></thead><tbody>${body.map((r) => `<tr>${cells(r).map((c) => `<td>${c}</td>`).join("")}</tr>`).join("")}</tbody></table>`);
      continue;
    }
    if (/^- /.test(l)) {
      const items = []; while (i < lines.length && /^- /.test(lines[i])) items.push(lines[i++].slice(2));
      out.push(`<ul>${items.map((x) => `<li>${inline(x)}</li>`).join("")}</ul>`); continue;
    }
    if (l.startsWith(">")) {
      const q = []; while (i < lines.length && lines[i].startsWith(">")) q.push(lines[i++].replace(/^>\s?/, ""));
      out.push(`<blockquote>${inline(q.join(" "))}</blockquote>`); continue;
    }
    const p = []; while (i < lines.length && lines[i].trim() && !/^(#|\||- |>)/.test(lines[i])) p.push(inline(lines[i++]));
    out.push(`<p>${p.join("<br>")}</p>`);
  }
  return out.join("\n");
}

const css = `:root{--bg:#f7f3e8;--card:#fffdf7;--ink:#1d2b25;--muted:#5b6b63;--gold:#a87a1e;--line:#e4dcc6;--emerald:#0b3a2d}
@media (prefers-color-scheme:dark){:root{--bg:#04201a;--card:#0b3a2d;--ink:#ecfdf5;--muted:#a7c4b8;--gold:#f3d27a;--line:#1d5a47}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--ink);font:16px/1.6 system-ui,-apple-system,"Segoe UI",sans-serif}
header{background:var(--emerald);color:#fff6d6;padding:28px 16px;text-align:center}header b{font-size:44px;font-family:"Scheherazade New","Amiri",serif}
header p{margin:4px 0 0;opacity:.85}nav{display:flex;gap:8px;justify-content:center;flex-wrap:wrap;margin-top:14px}nav a{color:#f3d27a;text-decoration:none;border:1px solid #f3d27a88;border-radius:999px;padding:4px 14px;font-size:14px}
main{max-width:1200px;margin:0 auto;padding:24px max(16px,env(safe-area-inset-left)) 48px;display:grid;grid-template-columns:1fr 1fr;gap:24px}
@media (max-width:860px){main{grid-template-columns:1fr}}
article{min-width:0;background:var(--card);border:1px solid var(--line);border-radius:18px;padding:8px 24px 24px}
article[dir=rtl]{font-family:"Scheherazade New","Amiri","Noto Naskh Arabic",serif;font-size:19px;line-height:1.8}
h1{color:var(--gold);font-size:1.6em;line-height:1.25}h2{font-size:1.15em;margin-top:1.6em;border-bottom:1px solid var(--line);padding-bottom:4px}h3{font-size:1.02em;margin-top:1.2em}
table{width:100%;border-collapse:collapse;font-size:.92em;display:block;overflow-x:auto}th,td{border:1px solid var(--line);padding:6px 8px;text-align:start;vertical-align:top}
blockquote{margin:16px 0;padding:12px 16px;border-inline-start:4px solid var(--gold);background:color-mix(in srgb,var(--gold) 10%,transparent);border-radius:8px;font-weight:600}
em{color:var(--muted)}`;

const nav = DOCS.map((d) => `<a href="${d.id}.html">${d.en} · ${d.ar}</a>`).join("");
mkdirSync("public/legal", { recursive: true });
for (const d of DOCS) {
  writeFileSync(`public/legal/${d.id}.html`, `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>${d.en} · ${d.ar} – Quran Muallem - معلم القرآن</title><style>${css}</style></head><body>
<header><b>معلم القرآن</b><small style="display:block;letter-spacing:.25em;font-size:13px;margin-top:4px">QURAN MUALLEM</small><p>${d.en} · ${d.ar}</p><nav>${nav}</nav></header>
<main><article lang="en" dir="ltr">${md(texts[d.id].en)}</article><article lang="ar" dir="rtl">${md(texts[d.id].ar)}</article></main></body></html>\n`);
}
writeFileSync("public/legal/index.html", `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Legal · المعلومات القانونية – Quran Muallem - معلم القرآن</title><style>${css}</style></head><body><header><b>معلم القرآن</b><small style="display:block;letter-spacing:.25em;font-size:13px;margin-top:4px">QURAN MUALLEM</small><p>Legal · المعلومات القانونية</p><nav>${nav}</nav></header></body></html>\n`);
console.log("✓ legal texts → src/lib/legalTexts.ts, public/legal/*.html");
