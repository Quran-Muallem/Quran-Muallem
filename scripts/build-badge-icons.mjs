// Generates src/lib/badgeIconData.ts: the inner SVG markup of the Lucide icons used by the surah
// badges (src/lib/surahBadges.ts), plus three custom drawings. Embedding the drawings keeps the
// badges independent of the installed lucide-react version.
// Usage: node scripts/build-badge-icons.mjs <path to a lucide checkout>/icons
import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2];
if (!dir) { console.error("usage: node scripts/build-badge-icons.mjs <lucide>/icons"); process.exit(1); }
const themes = fs.readFileSync("src/lib/surahBadges.ts", "utf8");
const keys = [...themes.matchAll(/^\s*\["([a-z0-9-]+)",/gm)].map((m) => m[1]);

const CUSTOM = {
  // The Kaaba with the gold band of the Kiswah and its door.
  kaaba: '<path d="M12 3 3 7v10l9 4 9-4V7z"/><path d="m3 7 9 4 9-4"/><path d="M12 11v10"/><path d="m3 10 9 4 9-4"/><path d="M15 16.7v-3.5l2.6-1.2v3.5"/>',
  // An elephant seen from the side, trunk lowered.
  elephant: '<path d="M3 17v-5a4 4 0 0 1 4-4h6.5a4.5 4.5 0 0 1 4.5 4.5V17"/><path d="M18 12.5c1.6 0 2.5 1 2.5 2.6V18a1.5 1.5 0 0 1-3 0"/><path d="M13.5 8.2a3 3 0 0 0 0 5.6"/><path d="M6 17v3"/><path d="M10 17v3"/><path d="M15 17v3"/><path d="M3 12 2 14.5"/><circle cx="16.2" cy="10.6" r=".6" fill="currentColor"/>',
  // A spider's web.
  "spider-web": '<path d="M12 2v20"/><path d="M2 12h20"/><path d="m4.9 4.9 14.2 14.2"/><path d="m19.1 4.9-14.2 14.2"/><path d="M12 6.5 15.9 8.1 17.5 12 15.9 15.9 12 17.5 8.1 15.9 6.5 12 8.1 8.1z"/><path d="M12 9.5 13.8 10.2 14.5 12 13.8 13.8 12 14.5 10.2 13.8 9.5 12 10.2 10.2z"/>',
};

const out = {};
for (const k of keys) {
  if (CUSTOM[k]) { out[k] = CUSTOM[k]; continue; }
  const f = path.join(dir, `${k}.svg`);
  if (!fs.existsSync(f)) throw new Error(`missing lucide icon ${k}`);
  const svg = fs.readFileSync(f, "utf8");
  out[k] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*\n\s*/g, "").trim();
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync("src/lib/badgeIconData.ts", `/**
 * Drawings of the surah badge symbols (24 × 24, stroke 2), generated by scripts/build-badge-icons.mjs.
 * Lucide icons © Lucide Contributors, ISC licence (https://lucide.dev/license).
 * "kaaba", "elephant" and "spider-web" are custom drawings in the same style.
 */
export const BADGE_ICONS = {
${body}
} as const;

export type BadgeIconKey = keyof typeof BADGE_ICONS;
`);
console.log(`wrote ${Object.keys(out).length} icons (${keys.length} themes)`);
